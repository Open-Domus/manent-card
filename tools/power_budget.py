"""First power budget. Every input is an estimate until measured; run to rewrite
docs/power-budget.md."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mechanical.card_mech.checks import envelope_report  # noqa: E402

V_CELL = 3.7          # nominal cell voltage
BUCK_EFF = 0.85       # assumed efficiency of the 1.8 V buck at these loads
USABLE = 0.80         # share of the rated capacity counted on
TARGET_HOURS, STRETCH_HOURS = 30, 40
CHARGE_C = 0.5        # charge current as a share of the capacity per hour: gentle on a thin cell
SLOT_SECONDS, SLOT_BYTES, FLASH_BITS = 0.1, 256, 2 ** 28

# (kind, name, low, nominal, high, source). "rail": milliwatts at the 1.8 V rail. "cell": milliamps from the cell.
RECORDING = [
    ("rail", "CPU, Opus at 15 / 30 / 50 % duty of 2.6 mA at 3 V", 1.15, 2.3, 3.9, "vendor figure x assumed duty"),
    ("rail", "PDM interface and 32 MHz oscillator", 1.5, 1.5, 1.5, "estimate"),
    ("rail", "Two microphones, 120 / 120 / 310 uA each at 1.8 V", 0.43, 0.43, 1.12, "datasheet"),
    ("rail", "Call sensor, 290 uA at 1.8 V; 700 uA if the clock were faster", 0.52, 0.52, 1.26, "product brief"),
    ("rail", "Flash program and erase, averaged", 0.36, 0.36, 0.5, "estimate"),
    ("cell", "Recording light, 0.3 / 0.5 / 1.0 mA", 0.3, 0.5, 1.0, "design choice"),
]
OFF = [
    ("rail", "Microcontroller asleep, clock and memory kept, 2 / 3 / 6 uA", 0.0036, 0.0054, 0.0108, "estimate"),
]
ALWAYS = [   # drawn in both states
    ("cell", "Bluetooth link kept alive", 0.010, 0.015, 0.030, "estimate"),
    ("cell", "Power chip itself", 0.001, 0.002, 0.005, "estimate"),
]
UPLOAD_MAH_PER_RECORDED_HOUR = 0.19   # 7.2 MB at an assumed 400 kbit/s
DAYS = {"1 h a day": 1, "3 h a day": 3, "8 h a day": 8}
SHIP_UA = 0.37


def at_cell(rows, col):
    """Milliamps from the cell for one column (0 low, 1 nominal, 2 high)."""
    return sum(r[2 + col] / BUCK_EFF / V_CELL if r[0] == "rail" else r[2 + col] for r in rows)


def recording_ma(col=1):
    return at_cell(RECORDING + ALWAYS, col) + UPLOAD_MAH_PER_RECORDED_HOUR


def hours(mah, col=1):
    return mah * USABLE / recording_ma(col)


def days(mah, hours_a_day, col=1):
    return mah * USABLE / (hours_a_day * recording_ma(col) + (24 - hours_a_day) * at_cell(OFF + ALWAYS, col))


def flash_hours():
    return FLASH_BITS / 8 / SLOT_BYTES * SLOT_SECONDS / 3600


def table(title, rows):
    out = [f"## {title}", "", "| Contributor | Low | Nominal | High | Source |", "| --- | --- | --- | --- | --- |"]
    out += [f"| {n} | {a:g} {u} | {b:g} {u} | {c:g} {u} | {s} |"
            for kind, n, a, b, c, s in rows for u in [("mW" if kind == "rail" else "mA")]]
    ma = [at_cell(rows, i) for i in range(3)]
    digits = 2 if ma[1] > 0.1 else 3
    return out + [f"| **At the cell** ({V_CELL} V, {BUCK_EFF:.0%} conversion of the rail terms) | "
                  + " | ".join(f"**{m:.{digits}f} mA**" for m in ma) + " | |", ""]


def main():
    cell = envelope_report("A")["cell"]["capacity_mah"]
    thin = envelope_report("B")["cell"]["capacity_mah"]
    cells = {f"{cell} mAh (the 3.5 mm card)": cell, f"{thin} mAh (a 3.0 mm card, if lower parts are found)": thin}
    out = ["# Power budget", "",
           "Generated by `tools/power_budget.py`. Nothing here is measured: the inputs are vendor",
           "figures, datasheet values and assumptions, each marked in the table. The first bench",
           "session on a development kit replaces them. Rows in mW are drawn from the 1.8 V rail,",
           "rows in mA straight from the cell.", ""]
    out += table("Switch on: recording", RECORDING + ALWAYS)
    out += table("Switch off: waiting, the phone still connected", OFF + ALWAYS)
    out += ["## Hours of recording on one charge", "",
            f"Usable capacity is taken as {USABLE:.0%} of the rating. Sending the audio to the phone costs",
            f"{UPLOAD_MAH_PER_RECORDED_HOUR} mAh per recorded hour and is counted in.", "",
            "| Cell | Low draw | Nominal | High draw |", "| --- | --- | --- | --- |"]
    out += [f"| {name} | " + " | ".join(f"{hours(mah, c):.0f} h" for c in range(3)) + " |" for name, mah in cells.items()]
    plaud_ma = 400 * USABLE / 30
    out += ["", f"The requirement is {TARGET_HOURS} hours, which is what Plaud publishes for its Note, and the stretch goal",
            f"{STRETCH_HOURS}, a working week of meetings. The budget says {hours(cell):.0f} at nominal draw and {hours(cell, 2):.0f} at the worst.",
            "", "**Do not promise these figures.** Plaud's 30 hours from 400 mAh mean about "
            f"{plaud_ma:.0f} mA while recording;", f"this budget says {recording_ma():.1f} mA. Plaud's card has Wi-Fi, 64 GB of storage and more microphones, which",
            "explains some of the distance; nobody here knows whether all of it. The largest term here, the Opus",
            "encoder's share of the processor, is a guess, and the same sum for the band came out at",
            "half of what `mnemo-band` had estimated on the older chip.", "",
            "## Days between charges", "",
            "| Recording | Low draw | Nominal | High draw |", "| --- | --- | --- | --- |"]
    out += [f"| {name} | " + " | ".join(f"{days(cell, h, c):.0f} days" for c in range(3)) + " |" for name, h in DAYS.items()]
    off_days = cell * USABLE / at_cell(OFF + ALWAYS, 2) / 24
    out += ["", f"On the {cell} mAh cell. Never switched on, the card stays connected for more than {off_days // 30:.0f} months even at the",
            f"high draw, and in ship mode ({SHIP_UA} uA, the power chip's documented figure) for years: in both cases the",
            "cell's own leakage decides.", "",
            "## What the flash holds", "",
            f"One {SLOT_BYTES}-byte slot holds {SLOT_SECONDS * 1000:.0f} ms of speech, so 256 Mbit is {FLASH_BITS // 8 // SLOT_BYTES:,} slots: "
            f"{int(flash_hours())} h {round(flash_hours() % 1 * 60)} min", "recorded with the phone out of reach. With the phone in reach the audio leaves as it is recorded",
            "and the flash never fills. The 512 Mbit and 1 Gbit parts fit the same pads, for two and four times as long.", "",
            "## Charging", "",
            f"The power chip is set to {cell * CHARGE_C:.0f} mA, half the cell's capacity per hour: about {1 / CHARGE_C * 1.25:.1f} hours from empty",
            "(constant current plus the tail, estimated). The chip can give 800 mA; what the cell accepts is on its",
            "datasheet, which nobody has yet.", "",
            "## What to measure first", "",
            "1. Opus encoder duty cycle on the nRF54L15 at complexity 0: it is the largest term and a guess.",
            "2. PDM and oscillator current while recording, with two microphones and the call sensor.",
            "3. Light: the current at which other people see it through the front skin, on a table and in daylight.",
            "4. Link current with the final connection interval, and what the 32.768 kHz crystal saves.",
            "5. Upload speed and energy for an hour of audio, card on the back of the phone.", ""]
    ROOT.joinpath("docs", "power-budget.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
