"""Rewrite docs/cost-estimate.md from the bill of materials and parts/prices.yaml."""
import csv
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parts" / "prices.yaml").read_text())
MURATA = ("LQP03", "GJM03")


def price_of(row):
    value, mpn = row["Value"], row["Part number"]
    if mpn.startswith(MURATA):
        return next(p for p in P["parts"] if p["match"] == "Murata RF")
    for p in P["parts"]:
        if p["match"] in (value, mpn) or mpn.startswith(p["match"]):
            return p
    assert not mpn or mpn == "to choose" or "pad" in row["Package"], row
    return None


def money(v):
    return f"{v:,.2f}" if v < 100 else f"{v:,.0f}"


def main():
    rows = [r for r in csv.DictReader((ROOT / "electrical" / "out" / "bom.csv").open()) if r["Fitted"] == "yes"]
    lines, passives, free = [], 0, 0
    for r in rows:
        n = int(r["Quantity"])
        if "pad" in r["Package"] or r["Value"].startswith("LiPo"):
            free += n
            continue
        p = price_of(r)
        if p is None:
            passives += n
        else:
            lines.append((f"{r['Value']}, {r['Part number']}" if r["Part number"] not in ("", "to choose", r["Value"]) else r["Value"], n, p))
    merged = {}
    for name, n, p in lines:
        key = p["match"]
        merged.setdefault(key, [name if key != "Murata RF" else "radio matching parts", 0, p])[1] += n
    lines = sorted(merged.values(), key=lambda l: -l[1] * l[2]["high"])
    low = sum(n * p["low"] for _, n, p in lines) + passives * P["passive"]["low"]
    high = sum(n * p["high"] for _, n, p in lines) + passives * P["passive"]["high"]
    o = ["# Cost estimate", "",
         "Generated by `tools/cost_estimate.py` from the bill of materials and `parts/prices.yaml`.",
         "US dollars, before tax, read or guessed on 2026-11-23. No supplier has been asked for a quote:",
         "the figures marked with a distributor are listings found through a search, the others are",
         "estimates. Each line has a low and a high figure; the truth may still be outside them.", "",
         "## One card, when a thousand are made", "", "### Parts on the board", "",
         "| Part | Pieces | Low | High | Source |", "| --- | --- | --- | --- | --- |"]
    o += [f"| {name} | {n} | {money(n * p['low'])} | {money(n * p['high'])} | {p['source']} |" for name, n, p in lines]
    o += [f"| resistors and capacitors | {passives} | {money(passives * P['passive']['low'])} | {money(passives * P['passive']['high'])} | {P['passive']['source']} |",
          f"| **Parts on the board** | | **{money(low)}** | **{money(high)}** | |", "",
          "The contact pads and the cell are not in this table: pads are copper, the cell is below.", "",
          "### Everything else", "", "| Item | Low | High | Source |", "| --- | --- | --- | --- |"]
    o += [f"| {r['item']} | {money(r['low'])} | {money(r['high'])} | {r['source']} |" for r in P["rest"]]
    rl, rh = sum(r["low"] for r in P["rest"]), sum(r["high"] for r in P["rest"])
    o += [f"| **Everything else** | **{money(rl)}** | **{money(rh)}** | |", "",
          f"**One card, in its box with sleeve and charger: {money(low + rl)} to {money(high + rh)} dollars.**", "",
          f"Hand work in Italy is the largest line, {money(P['rest'][6]['low'])} to {money(P['rest'][6]['high'])}; the electronics with board and assembly are",
          f"{money(low + P['rest'][0]['low'] + P['rest'][1]['low'])} to {money(high + P['rest'][0]['high'] + P['rest'][1]['high'])}. "
          "Shipping, duty, returns and the seller's margin are not counted.", "",
          "## Paid once", "", "| Item | Low | High | Source |", "| --- | --- | --- | --- |"]
    o += [f"| {r['item']} | {money(r['low'])} | {money(r['high'])} | {r['source']} |" for r in P["once"]]
    ol, oh = sum(r["low"] for r in P["once"]), sum(r["high"] for r in P["once"])
    o += [f"| **Paid once** | **{money(ol)}** | **{money(oh)}** | |", "",
          f"Spread over a thousand cards that is {money(ol / 1000)} to {money(oh / 1000)} dollars each, so the first thousand cost",
          f"{money(low + rl + ol / 1000)} to {money(high + rh + oh / 1000)} each. Approval for other markets (United States, United Kingdom) is not counted,",
          "nor is the work of designing what is not designed yet.", "",
          "## The first ten cards", "", "| Item | Low | High | Source |", "| --- | --- | --- | --- |"]
    o += [f"| {r['item']} | {money(r['low'])} | {money(r['high'])} | {r['source']} |" for r in P["prototypes"]]
    pl, ph = sum(r["low"] for r in P["prototypes"]), sum(r["high"] for r in P["prototypes"])
    o += [f"| **The first ten** | **{money(pl)}** | **{money(ph)}** | |", "",
          "Prototype services charge several times the thousand-piece price for parts, and a second",
          "round of boards is likely once the unread datasheets have been read.", "",
          "## Against what is sold", "",
          "Plaud sells its Note at 159 dollars and Amazon the Bee Eclipse at 99.99, the second with a",
          "subscription behind it. A common rule for hardware sold directly is a price of three to four",
          f"times what the thing costs to make: on {money(low + rl + ol / 1000)} to {money(high + rh + oh / 1000)} that is "
          f"{money(3 * (low + rl + ol / 1000))} to {money(4 * (high + rh + oh / 1000))} dollars.", "",
          "## What moves the figure most", "",
          "1. **Hand work.** Ten minutes more or less per card is worth more than any chip on the board.",
          "2. **The flash.** The 1 Gbit part first chosen is listed at about 15 dollars and out of stock:",
          "   more than the rest of the board. The 256 Mbit part adopted costs about a tenth and fits the same pads.",
          "3. **The call sensor.** It costs as much as the microcontroller. If the",
          "   first measurement shows it hears too little, leaving it off saves its price and nothing else changes.",
          "4. **The cell.** A custom size has a minimum order and a price nobody has quoted.",
          "5. **Volume.** At a hundred cards the parts cost about half as much again and the one-off costs",
          "   are a hundred dollars a card or more.", ""]
    (ROOT / "docs" / "cost-estimate.md").write_text("\n".join(o))
    print(f"docs/cost-estimate.md written: {money(low + rl)} to {money(high + rh)} a card at a thousand")


if __name__ == "__main__":
    main()
